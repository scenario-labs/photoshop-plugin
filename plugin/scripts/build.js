#!/usr/bin/env node
"use strict";
// Bundles plugin/src into plugin/dist/main.js: one script that UXP loads from
// index.html. Each source file becomes a function with its own module scope,
// so nothing the plugin declares can shadow a UXP global (a top-level
// `const URL` breaks UXP's WebSocket). Requires of relative paths are resolved
// at build time; any other name ("uxp", "photoshop", "os", "fs") goes to UXP's
// own require at run time. No eval, no code generation at run time.
//
// Release builds (the default) replace src/dev/* with stubs. --dev keeps the
// development-only pairing token and API key imports and the panel's UI loop
// (see AGENTS.md).

const fs = require("node:fs");
const path = require("node:path");

const PLUGIN = path.resolve(__dirname, "..");
const REPO = path.resolve(PLUGIN, "..");
const ROOTS = [path.join(PLUGIN, "src"), path.join(PLUGIN, "manifest.json"), path.join(REPO, "shared")];
const FLAGS = path.join(PLUGIN, "src", "build-flags.js");
const DEV_DIR = path.join(PLUGIN, "src", "dev") + path.sep;
const REQUIRE = /\brequire\(\s*(["'])([^"']+)\1\s*\)/g;
// What each development-only module becomes in a release bundle: the same
// exports, doing nothing, and no file name.
const DEV_STUBS = {
  "import-token.js": "{ importToken: async function () { return false; }, FILE: null }",
  "import-key.js": "{ importKey: async function () { return false; }, FILE: null, parse: null }",
  "ui-loop.js": "{ start: function () { return null; }, COMMAND: null, RESULT: null }",
  "ui-demo.js": "{ hook: function () { return null; }, run: null, DIR: null }",
  "live-run.js": "{ start: function () { return null; }, REQUEST: null, DIR: null }"
};

function inside(file) {
  return ROOTS.some((root) => file === root || file.startsWith(root + path.sep));
}

function resolveRequest(fromFile, request) {
  let target = path.resolve(path.dirname(fromFile), request);
  if (!fs.existsSync(target) && fs.existsSync(target + ".js")) target += ".js";
  if (!fs.existsSync(target)) throw new Error(`${path.relative(REPO, fromFile)}: cannot find ${request}`);
  if (!inside(target)) throw new Error(`${path.relative(REPO, fromFile)}: ${request} is outside plugin/src, plugin/manifest.json and shared/`);
  return target;
}

function sourceFor(file, dev) {
  if (file === FLAGS) return `"use strict";\nmodule.exports = ${JSON.stringify({ DEV: dev, BUILD: dev ? "dev" : "release" })};\n`;
  if (!dev && file.startsWith(DEV_DIR)) {
    const stub = DEV_STUBS[path.basename(file)];
    if (!stub) throw new Error(`${path.relative(REPO, file)}: no release stub for this development-only module`);
    return `"use strict";\n// Release build: development-only module removed.\nmodule.exports = ${stub};\n`;
  }
  const text = fs.readFileSync(file, "utf8");
  if (file.endsWith(".json")) return `module.exports = ${JSON.stringify(JSON.parse(text))};\n`;
  return text;
}

function bundle({ dev = false, entry = path.join(PLUGIN, "src", "entry.js") } = {}) {
  const modules = new Map();
  const order = [];
  function add(file) {
    if (modules.has(file)) return modules.get(file).id;
    const rec = { id: order.length, file, deps: {}, code: sourceFor(file, dev) };
    modules.set(file, rec);
    order.push(rec);
    if (!file.endsWith(".json")) {
      for (const m of rec.code.matchAll(REQUIRE)) {
        const request = m[2];
        if (request.startsWith("./") || request.startsWith("../")) rec.deps[request] = add(resolveRequest(file, request));
      }
    }
    return rec.id;
  }
  add(entry);
  const version = JSON.parse(fs.readFileSync(path.join(PLUGIN, "manifest.json"), "utf8")).version;
  const parts = [];
  parts.push(`/* Scenario for Photoshop ${version} (${dev ? "development" : "release"} build). MIT License. Generated by plugin/scripts/build.js from plugin/src and shared; do not edit. */`);
  parts.push("(function (hostRequire) {");
  parts.push('  "use strict";');
  parts.push("  var defs = [");
  order.forEach((rec, i) => {
    const rel = path.relative(REPO, rec.file).split(path.sep).join("/");
    parts.push(`    /* ${rec.id}: ${rel} */ [function (module, exports, require) {\n${rec.code}\n}, ${JSON.stringify(rec.deps)}]${i < order.length - 1 ? "," : ""}`);
  });
  parts.push("  ];");
  parts.push("  var cache = [];");
  parts.push("  function load(id) {");
  parts.push("    if (cache[id]) return cache[id].exports;");
  parts.push("    var module = { exports: {} };");
  parts.push("    cache[id] = module;");
  parts.push("    var def = defs[id];");
  parts.push("    def[0].call(module.exports, module, module.exports, function (name) {");
  parts.push("      if (Object.prototype.hasOwnProperty.call(def[1], name)) return load(def[1][name]);");
  parts.push("      return hostRequire(name);");
  parts.push("    });");
  parts.push("    return module.exports;");
  parts.push("  }");
  parts.push("  load(0);");
  parts.push('})(typeof require === "function" ? require : function (name) { throw new Error("no host module " + name); });');
  return { code: parts.join("\n") + "\n", files: order.map((r) => r.file), version };
}

function build({ dev = false, outFile } = {}) {
  outFile = outFile || path.join(PLUGIN, "dist", "main.js");
  const result = bundle({ dev });
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, result.code);
  return { ...result, outFile };
}

if (require.main === module) {
  const dev = process.argv.includes("--dev");
  const r = build({ dev });
  process.stdout.write(`built ${path.relative(REPO, r.outFile)} (${dev ? "dev" : "release"}, ${r.files.length} modules, ${r.code.length} bytes)\n`);
}

module.exports = { bundle, build };
